"""Train and evaluate all models, and write reports/model_report.md.

Run:  python -m ecom.models.train
"""

from __future__ import annotations

import logging
import time
from datetime import datetime

import pandas as pd

from ecom.config import REPORTS_DIR
from ecom.features import build_features
from ecom.models import delivery_time, forecast, review_risk

log = logging.getLogger("ecom.train")


def _md_table(df: pd.DataFrame, floatfmt: str = "{:,.3f}") -> str:
    cols = [df.index.name or ""] + list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, float) else str(v) for v in row]
        lines.append(f"| {idx} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def write_report(dt: dict, curve: pd.DataFrame, rr: dict, fc: pd.DataFrame) -> str:
    test_curve = (
        curve[curve["split"] == "test"]
        .set_index("policy")[["late_pct", "avg_promise_days"]]
        .rename_axis("policy")
    )
    rr_table = pd.DataFrame(rr["models"]).T.rename_axis("model")
    mae = pd.DataFrame({"MAE (days)": dt["test_mae_days"]}).rename_axis("model")
    q = dt["chosen_quantile"]
    olist_days, model_days = dt["test_olist_avg_promise_days"], dt["test_model_avg_promise_days"]
    return f"""# Model Report

_Generated by `python -m ecom.models.train` on {datetime.now():%Y-%m-%d %H:%M}._
All models use a **time-based split**: train Jan 2017 to Apr 2018, validate May 2018,
test Jun to Aug 2018. Test numbers are reported once, never tuned on.

## 1. Delivery-time model: route-level promises

LightGBM quantile regression at purchase time ({len(delivery_time.QUANTILES)} quantiles).
Promise = ceil(predicted quantile). The quantile is picked on validation (shortest promise
with a late rate no worse than Olist's): **P{q * 100:g}**.

| Test period (Jun to Aug 2018) | Olist today | Model P{q * 100:g} |
|---|---:|---:|
| Late deliveries | {dt["test_olist_late_pct"]:.2f}% | **{dt["test_model_late_pct"]:.2f}%** |
| Average promise | {olist_days:.1f} days | **{model_days:.1f} days** |

Point accuracy (median model vs baselines):

{_md_table(mae, "{:.2f}")}

Every candidate policy on the test period (the model curve vs Olist's single point):

{_md_table(test_curve, "{:.2f}")}

## 2. Negative-review risk model: day-0 alert at carrier handoff

Target: review score of 2 or lower (test base rate {rr["test_base_rate"]:.1%}).
"Top 10%" = acting on the 10% riskiest orders.

{_md_table(rr_table)}

## 3. Daily order forecast: 28-day capacity planning

Rolling-origin backtest, {forecast.FOLDS} folds x {forecast.HORIZON} days (May to Aug 2018,
including the May 2018 truckers' strike).

{_md_table(fc, "{:.2f}")}

## Limitations

- Test period orders arrive faster than training orders (Olist improved logistics in 2018).
  The time split exposes this drift instead of hiding it; production would retrain monthly.
- Reviews depend on product quality and expectations, which this data doesn't capture, so the risk
  model ranks well (lift) but can't be precise per order.
- Data after 21 Aug 2018 is truncated by the dataset extraction; the forecast stops there.
"""


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s",
                        datefmt="%H:%M:%S")  # fmt: skip
    t0 = time.perf_counter()

    log.info("Building leakage-safe features")
    feats = build_features()

    log.info("Training delivery-time quantile models")
    _, dt_metrics, curve = delivery_time.train(feats)

    log.info("Training review-risk models")
    _, rr_metrics, _ = review_risk.train(feats)

    log.info("Backtesting forecasts")
    series = forecast.daily_orders()
    folds, preds = forecast.backtest(series)
    fc_summary = forecast.summarise(folds, preds, series)

    REPORTS_DIR.mkdir(exist_ok=True)
    (REPORTS_DIR / "model_report.md").write_text(
        write_report(dt_metrics, curve, rr_metrics, fc_summary), encoding="utf-8"
    )
    log.info("Report -> reports/model_report.md (the app's models: python -m ecom.export_app)")
    log.info("Done in %.1fs", time.perf_counter() - t0)


if __name__ == "__main__":
    main()
