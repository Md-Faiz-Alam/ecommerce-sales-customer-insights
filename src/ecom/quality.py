"""Cleaning audit trail + data quality report.

Every cleaning rule records how many rows it touched, so the final report states
exactly what was changed and why. In a real team this is what a reviewer asks for.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

import pandas as pd


@dataclass
class Entry:
    table: str
    rule: str
    rows_affected: int
    action: str  # "fixed" | "flagged" | "dropped" | "derived" | "info"


@dataclass
class CleaningLog:
    entries: list[Entry] = field(default_factory=list)

    def add(self, table: str, rule: str, rows: int | bool, action: str) -> None:
        self.entries.append(Entry(table, rule, int(rows), action))

    def to_frame(self) -> pd.DataFrame:
        return pd.DataFrame([e.__dict__ for e in self.entries])


def write_report(
    path: Path,
    log: CleaningLog,
    row_counts: dict[str, tuple[int, int]],
    validation: dict[str, str],
) -> None:
    """Render the data-quality report as Markdown (readable directly on GitHub)."""
    lines = [
        "# Data Quality Report",
        "",
        f"_Generated by `python -m ecom.pipeline` on {datetime.now():%Y-%m-%d %H:%M}_",
        "",
        "## Row counts (raw → clean)",
        "",
        "| Table | Raw rows | Clean rows | Change |",
        "|---|---:|---:|---:|",
    ]
    for table, (raw, clean) in row_counts.items():
        lines.append(f"| {table} | {raw:,} | {clean:,} | {clean - raw:+,} |")

    lines += [
        "",
        "## Cleaning rules applied",
        "",
        "| Table | Rule | Rows | Action |",
        "|---|---|---:|---|",
    ]
    for e in log.entries:
        lines.append(f"| {e.table} | {e.rule} | {e.rows_affected:,} | {e.action} |")

    lines += ["", "## Validation (pandera contracts + referential integrity)", ""]
    lines += [f"- **{name}**: {status}" for name, status in validation.items()]
    lines.append("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
